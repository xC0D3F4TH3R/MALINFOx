# ─────────────────────────────────────────────────────────────────────────────
# MAIN ENTRY POINT
# ─────────────────────────────────────────────────────────────────────────────

main() {
    case "$PLATFORM" in
        selfhosted|local)
            deploy_selfhosted
            ;;
        fly|flyio)
            deploy_fly
            ;;
        railway)
            deploy_railway
            ;;
        render)
            log_error "Render deployment not automated. Use Render dashboard with DEPLOYMENT.md guide."
            exit 1
            ;;
        *)
            echo "Usage: $0 [selfhosted|fly|railway|render] [domain] [admin-email] [admin-password]"
            echo ""
            echo "Platforms:"
            echo "  selfhosted  - Deploy on your own VM (full control, KVM support for VM orchestrator)"
            echo "  fly         - Deploy to Fly.io (free tier, KVM support for VM orchestrator)"
            echo "  railway     - Deploy to Railway (easiest, free tier, NO KVM)"
            echo "  render      - Deploy to Render (manual via dashboard)"
            echo ""
            echo "Arguments:"
            echo "  domain         - Your domain (e.g., malinfo.myagency.gov)"
            echo "  admin-email    - Initial admin email (optional, will prompt)"
            echo "  admin-password - Initial admin password (optional, will prompt)"
            echo ""
            echo "Examples:"
            echo "  $0 selfhosted malinfo.myagency.gov admin@myagency.gov 'SecurePass123!'"
            echo "  $0 fly malinfo.myagency.gov"
            echo "  $0 railway malinfo.myagency.gov"
            exit 1
            ;;
    esac
}

main "$@"